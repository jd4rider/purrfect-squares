#!/usr/bin/env node
/*
 * Bake the Journey catalogue.
 *
 *   node scripts/bake-levels.mjs [--sample]
 *
 * Every board is generated from a stable seed, then accepted only when the
 * solver finds exactly one partition. The validated solution is stored with the
 * level so hints can never point at a guess.
 */
import { writeFile } from 'node:fs/promises'
import { generatePuzzle } from '../src/puzzle/generator.js'

const CHAPTERS = [
  { name: 'Sunny Start', theme: 'garden', size: [4, 4], cats: [4, 5] },
  { name: 'Window Sills', theme: 'cottage', size: [5, 5], cats: [5, 7] },
  { name: 'Cushion Corners', theme: 'cottage', size: [6, 5], cats: [6, 8] },
  { name: 'Moonlit Mats', theme: 'moonlight', size: [6, 6], cats: [7, 9] },
  { name: 'Patchwork Paths', theme: 'cottage', size: [6, 6], cats: [8, 10] },
  { name: 'Sugar Windows', theme: 'candy', size: [7, 6], cats: [9, 11] },
  { name: 'Palace Halls', theme: 'palace', size: [7, 7], cats: [10, 12] },
  { name: 'Purrfect Master', theme: 'palace', size: [8, 7], cats: [11, 13] },
]

const SHAPES = [
  ['rect', 'rect', 'rect', 'l', 't'],
  ['rect', 'rect', 'l', 'z', 't'],
  ['rect', 'l', 't', 'z', 'stairs'],
  ['l', 't', 'z', 'stairs', 'cross'],
  ['t', 'z', 'stairs', 'cross', 'u'],
  ['z', 'stairs', 'cross', 'u', 'blob'],
  ['stairs', 'cross', 'u', 'blob', 't'],
  ['cross', 'u', 'blob', 'stairs', 'z'],
]

const NAMES = [
  'First Stretch', 'Warm Windowsill', 'Sunbeam Nap', 'Two Little Paws', 'Garden Watch',
  'Pillow Fort', 'Tea Time', 'Quiet Corner', 'Dusty Bookshelf', 'Lazy Afternoon',
  'Knit and Purr', 'Sleepy Shelf', 'Cardboard Box', 'Paper Sunbeam', 'Soft Landing',
  'Mittens', 'Window Seat', 'Little Lantern', 'Night Watch', 'Moonbeam',
  'Star Paws', 'Blue Hour', 'Velvet Cushion', 'Hush', 'Dreaming',
]

const total = CHAPTERS.length * 25
const sample = process.argv.includes('--sample')
const count = sample ? 6 : total
const output = []
const startedAt = Date.now()

for (let index = 0; index < count; index += 1) {
  const chapter = Math.min(CHAPTERS.length - 1, Math.floor(index / 25))
  const withinChapter = index % 25
  const config = CHAPTERS[chapter]
  const [width, height] = config.size
  // Difficulty climbs across the whole catalogue, not only within a chapter.
  const ease = index / Math.max(1, count - 1)
  const minCats = Math.max(3, config.cats[0] - (1 - ease > 0.6 ? 1 : 0))
  const maxCats = Math.min(14, config.cats[1] + (ease > 0.7 ? 1 : 0))
  const shapes = SHAPES[chapter]
  const shape = withinChapter < 5 ? 'rect' : shapes[withinChapter % shapes.length]

  let generated = null
  let attempt = 0
  while (!generated && attempt < 6) {
    generated = generatePuzzle({
      seed: `purrfect-${chapter + 1}-${withinChapter}-${attempt}`,
      width,
      height,
      shape,
      minCats,
      maxCats,
      attempts: 70,
      maxNodes: 150000,
    })
    attempt += 1
  }

  if (!generated) {
    console.error(`level ${index + 1}: no unique puzzle found, stopping`)
    process.exit(1)
  }

  const id = `j${String(index + 1).padStart(3, '0')}`
  const name = `${NAMES[withinChapter % NAMES.length]}`
  output.push({
    id,
    name,
    chapter: chapter + 1,
    chapterName: config.name,
    theme: config.theme,
    width,
    height,
    mask: generated.level.mask,
    cats: generated.level.cats,
    difficulty: generated.level.difficulty,
    seed: generated.level.seed,
    solution: generated.solution,
    stats: { candidates: generated.stats.totalCandidates, branch: generated.stats.maxBranch },
  })

  if ((index + 1) % 10 === 0 || sample) {
    console.log(
      `  ${id} ${generated.level.mask[0].length}×${generated.level.mask.length} ` +
        `${generated.level.cats.length} cats difficulty ${generated.level.difficulty} ` +
        `(try ${generated.attempts}, ${generated.stats.nodes} nodes)`,
    )
  }
}

if (!sample) {
  const body = output
    .map(
      (level) =>
        `  ${JSON.stringify(
          {
            id: level.id,
            name: level.name,
            chapter: level.chapter,
            theme: level.theme,
            width: level.width,
            height: level.height,
            mask: level.mask,
            cats: level.cats,
            difficulty: level.difficulty,
            seed: level.seed,
            solution: level.solution,
          },
        )},`,
    )
    .join('\n')

  const file = `// Generated by scripts/bake-levels.mjs — every board is unique-solution
// verified by the solver. Do not hand-edit; re-run the script instead.
export const JOURNEY_LEVELS = [
${body}
]
`
  await writeFile(new URL('../src/levels/data.js', import.meta.url), file)
  const elapsed = ((Date.now() - startedAt) / 1000).toFixed(1)
  console.log(`baked ${output.length} unique levels in ${elapsed}s -> src/levels/data.js`)
} else {
  console.log(JSON.stringify(output[0], null, 2).slice(0, 800))
}
